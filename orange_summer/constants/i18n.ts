export type Langue = 'fr' | 'en' | 'es' | 'de' | 'pt' | 'ar';

export const LANGUES: { code: Langue; nom: string; rtl: boolean }[] = [
  { code: 'fr', nom: 'Français', rtl: false },
  { code: 'en', nom: 'English', rtl: false },
  { code: 'es', nom: 'Español', rtl: false },
  { code: 'de', nom: 'Deutsch', rtl: false },
  { code: 'pt', nom: 'Português', rtl: false },
  { code: 'ar', nom: 'العربية', rtl: true },
];

export function estRtl(langue: Langue): boolean {
  return LANGUES.find((l) => l.code === langue)?.rtl ?? false;
}

